// Screen definitions. Every list, form, child grid and Excel import is driven by these.
import type { ColType, ExportColumn } from './exporters';
import type { Filters, LookupDef, Row } from './data';
import { fmtDate, fmtNum, todayISO } from './format';

export type FieldType = 'text' | 'textarea' | 'money' | 'number' | 'qty' | 'int' | 'pct' | 'date' | 'select' | 'lookup' | 'checkbox' | 'tags';

export interface FieldDef {
  name: string;
  label: string;
  type: FieldType;
  required?: boolean;
  options?: (string | { value: string; label: string })[];
  lookup?: LookupDef;
  /** narrows lookup choices using the form values and the parent record (for child grids) */
  lookupFilter?: (values: Row, parent: Row | null, parentKey: string | null) => Filters;
  default?: unknown | (() => unknown);
  help?: string;
  span?: 1 | 2 | 3;
  readOnlyOnEdit?: boolean;
  showIf?: (values: Row) => boolean;
}

export interface ColumnDef extends ExportColumn {
  type?: ColType;
  currencyKey?: string;
}

export interface ChildDef {
  entity: string;
  fk: string;            // column in the child's list source that points at the parent
  presetFk?: string | null; // column set on new child rows (defaults to fk; null = none)
  title?: string;
  readOnly?: boolean;
  presets?: (parent: Row) => Row;
}

export interface EntityDef {
  key: string;
  table: string;
  view?: string;
  title: string;
  singular: string;
  group: 'masters' | 'export' | 'import' | 'bond' | 'incentive' | 'finance';
  fields: FieldDef[];
  columns: ColumnDef[];
  order?: { column: string; ascending?: boolean }[];
  search: string[];
  statuses?: string[];
  detail?: boolean;
  children?: ChildDef[];
  summary?: ColumnDef[];
  noCreate?: boolean;
  importable?: boolean;
  quickFilters?: { label: string; filters: Filters }[];
  /** extra columns to read from the list source for record pages */
  titleOf?: (r: Row) => string;
}

